//! hash — the two digests the Python engine gets from `hashlib`.
//!
//! `cs_parser.py` builds every string-literal node id as
//! `'#str:' + hashlib.md5(value.encode('utf-8', 'replace')).hexdigest()[:16]`,
//! so a byte-identical clone has to implement MD5 itself (no crate is allowed).
//! `cs_doc.py` uses `hashlib.sha1` for its edit fingerprints, so SHA-1 lives
//! here too.
//!
//! Both are plain, unoptimised implementations of RFC 1321 and RFC 3174; they
//! are checked against Python's `hashlib` and the published test vectors in the
//! unit tests at the bottom of this file.

